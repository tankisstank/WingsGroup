import 'dotenv/config'

import fs from 'node:fs/promises'
import path from 'node:path'

import {
  parseArgs,
  parseDoicanhvietRecord,
  annotateDuplicateCandidates,
  readCrawlerRecords,
  selectedSourceIDs,
  type NormalizedTour,
} from './lib/doicanhviet'

const repoRoot = path.resolve(import.meta.dirname, '..', '..')
const defaultCrawlerRoot = process.env.DOICANHVIET_ROOT || 'E:\\repo\\doicanhviet-crawler'
const defaultArtifactDir = path.join(repoRoot, 'artifacts', 'imports', 'doicanhviet')

const markdownCell = (value: unknown) =>
  String(value ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ')

const buildReview = (records: NormalizedTour[]) => {
  const lines = [
    '# Doicanhviet import review',
    '',
    '> Generated by `parse-doicanhviet.ts`. Do not edit `tours.normalized.json`; record decisions in `import-decisions.json`.',
    '',
    '| Source ID | Kind | Title | Market | Duration | Itinerary | Departures | Media | Warnings | Blocking errors |',
    '| --- | --- | --- | --- | --- | ---: | ---: | ---: | --- | --- |',
  ]
  for (const record of records) {
    lines.push(
      `| ${markdownCell(record.sourceId)} | ${record.kind} | ${markdownCell(record.title)} | ${record.market || '—'} | ${record.durationDays || '—'}D/${record.durationNights ?? '—'}N | ${record.itineraryDays.length} | ${record.departures.length} | ${record.images.length} | ${markdownCell(record.warnings.join(', ')) || '—'} | ${markdownCell(record.blockingErrors.join(', ')) || '—'} |`,
    )
  }
  const counts = records.reduce(
    (result, record) => {
      result[record.kind] += 1
      if (!record.market && record.kind === 'tour') result.unmappedMarket += 1
      if (!record.publishEligible && record.kind === 'tour') result.draftOnly += 1
      return result
    },
    { tour: 0, news: 0, pagination: 0, invalid: 0, unmappedMarket: 0, draftOnly: 0 } as Record<
      string,
      number
    >,
  )
  lines.push('', '## Summary', '', '```json', JSON.stringify(counts, null, 2), '```', '')
  return `${lines.join('\n')}\n`
}

const main = async () => {
  const args = parseArgs(process.argv.slice(2))
  const crawlerRoot = path.resolve(String(args['crawler-root'] || defaultCrawlerRoot))
  const artifactDir = path.resolve(String(args['artifact-dir'] || defaultArtifactDir))
  const only = args.only ? selectedSourceIDs(args.only) : undefined
  const limit = args.limit ? Number(args.limit) : undefined
  if (limit !== undefined && (!Number.isInteger(limit) || limit < 1)) {
    throw new Error('--limit must be a positive integer')
  }

  const sourceRecords = await readCrawlerRecords(crawlerRoot, only)
  const selected = limit ? sourceRecords.slice(0, limit) : sourceRecords
  const normalized: NormalizedTour[] = []
  for (const { file, record } of selected) {
    normalized.push(
      await parseDoicanhvietRecord({
        crawlerRoot,
        record,
        sourceFile: path.relative(crawlerRoot, file),
      }),
    )
  }
  annotateDuplicateCandidates(normalized)
  normalized.sort((left, right) =>
    left.sourceId.localeCompare(right.sourceId, 'en', { numeric: true }),
  )

  await fs.mkdir(artifactDir, { recursive: true })
  await fs.writeFile(
    path.join(artifactDir, 'tours.normalized.json'),
    `${JSON.stringify(normalized, null, 2)}\n`,
    'utf8',
  )
  await fs.writeFile(path.join(artifactDir, 'import-review.md'), buildReview(normalized), 'utf8')
  await fs.writeFile(
    path.join(artifactDir, 'media-manifest.json'),
    `${JSON.stringify(
      normalized.flatMap((record) => record.images),
      null,
      2,
    )}\n`,
    'utf8',
  )

  console.log(
    JSON.stringify(
      {
        artifactDir,
        crawlerRoot,
        records: normalized.length,
        tours: normalized.filter((record) => record.kind === 'tour').length,
        news: normalized.filter((record) => record.kind === 'news').length,
        pagination: normalized.filter((record) => record.kind === 'pagination').length,
        invalid: normalized.filter((record) => record.kind === 'invalid').length,
      },
      null,
      2,
    ),
  )
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
